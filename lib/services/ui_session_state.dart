// ui_session_state.dart
// จำ "การตั้งค่าการแสดงผล" ชั่วคราวไว้ตลอดอายุของแอป (in-memory ล้วนๆ ไม่เขียน
// ลงดิสก์) — เช่น พับ/ขยายเมนูด่วน, ตัวกรองที่เลือกไว้, มุมมองตาราง/กริด,
// คอลัมน์ที่ซ่อน/แสดง ฯลฯ เดิมแต่ละหน้าเก็บเป็น State field ธรรมดา ซึ่งหายไปทุก
// ครั้งที่สลับหน้าออกแล้วกลับมา เพราะ AppShell ทำลาย/สร้าง State ของแต่ละหน้า
// ใหม่ทุกครั้ง (ไม่มี IndexedStack คงสภาพไว้) — ผู้ใช้คาดหวังว่าค่าที่เลือกไว้
// ควรอยู่แบบนั้นจนกว่าจะปิดแอปทั้งโปรแกรมแล้วเปิดใหม่ ไม่ใช่รีเซ็ตทุกครั้งที่
// แค่สลับเมนู จึงเก็บไว้ที่ singleton ตัวนี้แทนที่จะเก็บใน State ของแต่ละหน้าตรงๆ
//
// ตั้งใจไม่ใช้ SharedPreferences — ถ้าปิดแอปจริงๆ แล้วเปิดใหม่ ต้องการให้กลับไป
// เป็นค่าเริ่มต้นเสมอ (ตามที่ผู้ใช้ระบุไว้) ไม่ใช่จำข้ามการเปิดแอปครั้งใหม่

class UiSessionState {
  UiSessionState._();
  static final UiSessionState instance = UiSessionState._();

  final Map<String, Object?> _values = {};

  /// อ่านค่าที่เคยเก็บไว้ (ถ้ามี) ไม่งั้นคืนค่าเริ่มต้นที่ส่งมา
  T read<T>(String key, T fallback) {
    final v = _values[key];
    return v is T ? v : fallback;
  }

  void write(String key, Object? value) => _values[key] = value;
}
